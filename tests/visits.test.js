test('manual visit uses independent confirmation and stable current-detail identity', () => {
  let current = company(); let kind = 'detail'; let subject = 'job:a';
  const href = 'https://www.zhipin.com/web/geek/job';
  const state = api.createPageState(() => ({ kind, detailType: 'job', source: 'job-card-match', current, subject }), () => href, 'doc');
  const first = state.refresh();
  assert.ok(state.confirmManual(first.token, current.key, first.visitId));
  assert.equal(state.confirmVisit(first.token, current.key, first.visitId), null);
  current = null; state.refresh(); current = company();
  assert.equal(state.refresh().visitId, first.visitId);
  subject = 'job:b';
  assert.notEqual(state.refresh().visitId, first.visitId);
  assert.equal(state.confirmManual(first.token, current.key, first.visitId), null);
  kind = 'list'; current = null; state.refresh(); kind = 'detail'; current = company();
  assert.notEqual(state.refresh().visitId, first.visitId);
});
test('manual sessions preserve first time across repeat/worker restart; undo permits deliberate resave', async () => {
  const storage = memoryStorage(); const session = memoryStorage();
  const repository = api.createRepository(storage); let visits = api.createVisits(repository, session);
  const snapshot = { visitId: 'manual:1', current: company() };
  const first = await visits.manual(7, snapshot, async () => {});
  assert.equal(first.state, 'manual');
  visits = api.createVisits(api.createRepository(storage), session);
  assert.equal((await visits.manual(7, snapshot, async () => {})).state, 'manual');
  const next = await visits.manual(8, { ...snapshot, visitId: 'manual:2' }, async () => {});
  assert.equal(next.state, 'prior'); assert.equal(next.markedAt, first.markedAt);
  await visits.remove(company().key);
  assert.deepEqual(storage.data, {});
  assert.equal((await visits.manual(7, snapshot, async () => {})).state, 'manual');
  assert.equal((await repository.list()).length, 1);
});
