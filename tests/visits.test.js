test('current visit undo stays suppressed, new visit records again, concurrent companies are independent', async () => {
  const storage = memoryStorage(); const session = memoryStorage();
  const repository = api.createRepository(storage); const visits = api.createVisits(repository, session);
  const a = { visitId: 'a:1', current: company() }; const b = { visitId: 'b:1', current: company(ID_B) };
  await Promise.all([visits.open(7, a, async () => {}), visits.open(8, b, async () => {})]);
  await visits.remove(a.current.key);
  assert.equal((await visits.open(7, a, async () => {})).state, 'suppressed');
  assert.equal((await repository.list()).length, 1);
  assert.equal((await visits.open(7, { ...a, visitId: 'a:2' }, async () => {})).state, 'first');
  assert.equal((await repository.list()).length, 2);
});
test('navigation verification and storage failures do not fabricate success; failed undo preserves original record', async () => {
  const storage = memoryStorage(); const session = memoryStorage();
  const repository = api.createRepository(storage); const visits = api.createVisits(repository, session);
  const a = { visitId: 'a:1', current: company() };
  let calls = 0;
  await assert.rejects(visits.open(7, a, async () => { if (++calls === 2) throw new Error('page switched before write'); }), /page switched/);
  assert.deepEqual(storage.data, {});
  storage.fail('set'); await assert.rejects(visits.open(7, a, async () => {}), /保存失败/);
  storage.fail(null); await visits.open(7, a, async () => {});
  storage.fail('remove'); await assert.rejects(visits.remove(company().key), /撤销失败/);
  storage.fail(null);
  assert.equal((await repository.list()).length, 1);
  assert.equal((await visits.open(7, a, async () => {})).state, 'first');
  session.fail('set'); await assert.rejects(visits.remove(company().key), /保存失败/);
  assert.equal((await repository.list()).length, 1);
});
